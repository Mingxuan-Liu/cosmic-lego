export function buildExample() {
  const context = buildScene({ registry: createRegistry(), createLayer: createWorkspaceLayer });
  const draft = context.project.begin(), overlays = context.layer.author(draft), science = context.binding.author(draft);
  const magnitude = science.map('magnitude', 'moving-collection', { id: 'position-magnitudes' });
  const mean = science.reduce('mean', magnitude, { id: 'mean-position-magnitude' });
  const collection = overlays.plot({ id: 'positions-plot', title: 'Point positions · X',
    x: 30, y: 20, width: 390, height: 270, component: 0 });
  overlays.bind(collection, 'moving-collection', { component: 0 });
  const derived = overlays.plot({ id: 'mean-plot', title: 'Mean position magnitude',
    x: 440, y: 20, width: 360, height: 240, hidden: true });
  overlays.bind(derived, mean);
  overlays.inspector({ id: 'inspector', title: 'Selected object', x: 1000, y: 20, width: 330, height: 310 });
  overlays.provenance({ id: 'provenance', title: 'Models and provenance', x: 30, y: 380, width: 320, height: 180, folded: true });
  overlays.conversation({ id: 'conversation', title: 'Conversation', x: 1000, y: 340, width: 360, height: 400 });
  draft.accept();
  // A loaded example starts with a clean user-edit history. Future edits still
  // use the same accepted graph and ordinary F01 Undo/Redo transactions.
  context.project = Project.from(context.project.snapshot(), { validators: context.layer.validators });
  return context;
}

export async function evaluateWorkspace(context, runtime, time = { value: 0, unit: 's' }, capabilities, isCurrent = () => true) {
  const identity = context.project.token, results = [];
  const failure = diagnostics => ({ identity, time, results, snapshot: {
    valid: false, identity, time,
    scene: { valid: false, identity, time, nodes: [], assets: [], bindings: [], diagnostics },
    overlays: [], diagnostics,
  } });
  for (const source of context.layer.sources(context.project)) {
    if (!isCurrent()) return failure([{ code: 'STALE_RESULT', path: '$', message: 'A newer workspace sample superseded this request.' }]);
    const result = await runtime.submit(context.project, source.nodeId, { port: source.port, time }).promise;
    results.push(result);
    if (!result.valid) return failure(result.diagnostics);
  }
  if (!isCurrent()) return failure([{ code: 'STALE_RESULT', path: '$', message: 'A newer workspace sample superseded this request.' }]);
  const snapshot = await context.layer.compile(context.project, { results, time, capabilities });
  return { identity, time, results, snapshot };
}

export async function demonstrate() {
  const context = buildExample(), runtime = createRuntime({ registryModule });
  try {
    const initial = await evaluateWorkspace(context, runtime, { value: 2, unit: 's' });
    assert.equal(initial.snapshot.valid, true, JSON.stringify(initial.snapshot.diagnostics));
    assert.equal(initial.snapshot.overlays.length, 5);
    assert.deepEqual(context.project.history, { canUndo: false, canRedo: false });
    const positions = initial.results.find(result => result.producer.nodeId === 'moving-collection').value;
    const mean = initial.results.find(result => result.producer.nodeId === 'mean-position-magnitude').value;
    const expected = positions.data.reduce((sum, row) => sum + Math.hypot(...row), 0) / positions.data.length;
    assert.ok(Math.abs(mean.data - expected) < 1e-12);
    assert.equal(initial.snapshot.overlays.find(overlay => overlay.id === 'mean-plot').hidden, true);

    const draft = context.project.begin(), author = context.layer.author(draft);
    const field = author.plot({ id: 'field-plot', title: 'Temperature samples', x: 440, y: 300, width: 390, height: 270 });
    author.bind(field, 'scalar-field');
    const copy = author.duplicate(field, { id: 'field-plot-copy', title: 'Independent temperature view', hidden: true });
    const edges = draft.snapshot().nodes.filter(node => node.type === 'workspace.plot-source');
    assert.equal(edges.find(edge => edge.references.target === copy.id).references.source,
      edges.find(edge => edge.references.target === field.id).references.source);
    draft.accept();
    const added = await evaluateWorkspace(context, runtime, { value: 2, unit: 's' });
    assert.equal(added.snapshot.valid, true, JSON.stringify(added.snapshot.diagnostics));
    assert.equal(added.snapshot.overlays.length, 7);
    assert.deepEqual(added.snapshot.overlays.find(overlay => overlay.id === 'field-plot').data,
      added.results.find(result => result.producer.nodeId === 'scalar-field').value);
    assert.deepEqual(added.results.find(result => result.producer.nodeId === 'moving-collection').value, positions);

    const removal = context.project.begin(), removing = context.layer.author(removal);
    removing.remove('field-plot'); removing.remove('field-plot-copy'); removal.accept();
    assert.equal((await evaluateWorkspace(context, runtime, { value: 2, unit: 's' })).snapshot.overlays.length, 5);
    context.project.undo(context.project.token);
    assert.equal((await evaluateWorkspace(context, runtime, { value: 2, unit: 's' })).snapshot.overlays.length, 7);
    context.project.redo(context.project.token);
    assert.equal((await evaluateWorkspace(context, runtime, { value: 2, unit: 's' })).snapshot.overlays.length, 5);
    return { overlays: 5, derivedMeanPositionMagnitude: mean.data, independentFieldPlots: true,
      unchangedScientificValues: true, removalUndoRedo: true };
  } finally { await runtime.dispose(); }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) console.log(JSON.stringify(await demonstrate(), null, 2));
